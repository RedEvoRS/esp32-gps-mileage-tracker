"""Check committed Python locks without installing packages or using the network."""

from pathlib import Path
import re
import unittest


SERVER = Path(__file__).resolve().parents[1]
SERVICES = ("mileage-ingest", "mileage-viewer")
PIN = r"([A-Za-z0-9][A-Za-z0-9._-]*)==([0-9][A-Za-z0-9.!+_-]*)"
HASH = r"--hash=sha256:[a-f0-9]{64}"


def requirements(text, *, hashed):
    """Read pip-compile's continued entries, rejecting unreviewed pip options."""
    result = {}
    pending = ""
    for line in text.splitlines():
        line = line.partition("#")[0].strip()
        if not line:
            continue
        pending += line.removesuffix("\\").strip() + " "
        if line.endswith("\\"):
            continue
        pattern = PIN + (rf"(?:\s+{HASH})+" if hashed else "")
        match = re.fullmatch(pattern, pending.strip())
        if not match:
            raise ValueError(f"Expected an exact pin{' with SHA-256 hashes' if hashed else ''}: {pending.strip()}")
        name, version = match.groups()
        name = re.sub(r"[-_.]+", "-", name).lower()
        if name in result:
            raise ValueError(f"Duplicate package: {name}")
        result[name] = version
        pending = ""
    if pending or not result:
        raise ValueError("Incomplete or empty requirements")
    return result


class PythonRequirements(unittest.TestCase):
    def test_locks_are_hashed_exact_pins_and_match_direct_inputs(self):
        for service in SERVICES:
            with self.subTest(service=service):
                directory = SERVER / service
                lock = requirements((directory / "requirements.txt").read_text(), hashed=True)
                inputs = (directory / "requirements.in").read_text().splitlines()
                direct = requirements("\n".join(inputs), hashed=False)
                for name, version in direct.items():
                    self.assertEqual(lock.get(name), version, f"{service}: {name}")

    def test_shared_packages_have_the_same_version(self):
        ingest, viewer = [requirements((SERVER / service / "requirements.txt").read_text(), hashed=True)
                          for service in SERVICES]
        shared = ingest.keys() & viewer.keys()
        self.assertTrue(shared)
        for name in shared:
            with self.subTest(package=name):
                self.assertEqual(ingest[name], viewer[name])

    def test_rejects_unpinned_unhashed_and_duplicate_entries(self):
        digest = "--hash=sha256:" + "0" * 64
        for entry in ("flask>=3.1.3 " + digest, "flask==3.* " + digest,
                      "flask==3.1.3", "flask==3.1.3 --hash=sha256:bad",
                      "-r other.txt", "flask==3.1.3 " + digest + " \\",
                      f"Flask==3.1.3 {digest}\nflask==3.1.3 {digest}"):
            with self.subTest(entry=entry), self.assertRaises(ValueError):
                requirements(entry, hashed=True)

    def test_dependabot_header_and_runtime_context(self):
        ignore = (SERVER / ".dockerignore").read_text().splitlines()
        for service in SERVICES:
            with self.subTest(service=service):
                directory = SERVER / service
                lock = (directory / "requirements.txt").read_text()
                self.assertIn("# This file is autogenerated by pip-compile with Python 3.12\n", lock)
                self.assertIn("--output-file=requirements.txt requirements.in", lock)
                self.assertIn(f"!{service}/requirements.txt", ignore)
                self.assertNotIn(f"!{service}/requirements.in", ignore)
                self.assertIn("--require-hashes -r requirements.txt", (directory / "Dockerfile").read_text())
        self.assertNotIn("!update_python_dependencies.sh", ignore)


if __name__ == "__main__":
    unittest.main()
