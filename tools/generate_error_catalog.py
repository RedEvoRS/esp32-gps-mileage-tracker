#!/usr/bin/env python3
"""Generate the sketch-local, Arduino-independent diagnostic lookup table."""

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))
from common.diagnostics.catalog import load_catalog  # noqa: E402

OUTPUT = ROOT / "firmware" / "04_trip_logger" / "diag_catalog.h"


def catalog_digest(catalog):
    """Fingerprint all definitions, independent of JSON whitespace/key order."""
    return hashlib.sha256(json.dumps(catalog["codes"], sort_keys=True,
                                     separators=(",", ":")).encode("utf-8")).hexdigest()


def render(catalog):
    quote = lambda text: json.dumps(text, ensure_ascii=True)
    rows = sorted(catalog["codes"], key=lambda row: row["code"])
    lines = [
        "// Generated by tools/generate_error_catalog.py; do not edit.",
        "#ifndef MILEAGE_DIAG_CATALOG_H", "#define MILEAGE_DIAG_CATALOG_H",
        "#include <cstddef>", "#include <cstdint>", "", "namespace diagnostics {",
        f'constexpr std::uint16_t kCatalogVersion = {catalog["catalog_version"]};',
        f'constexpr char kCatalogDigest[] = "{catalog_digest(catalog)}";',
        "enum class Severity : std::uint8_t { Info, Warning, Error, Critical };",
        "enum class Journal : std::uint8_t { PerOccurrence, Transitions, Counter };",
        "enum class Code : std::uint16_t {",
    ]
    lines += [f'    {row["symbol"]} = {row["code"]},' for row in rows]
    lines += ["};", "struct CatalogEntry {", "    Code code;", "    const char* symbol;",
              "    Severity severity;", "    const char* oled[3];",
              "    std::uint8_t oled_line_count;", "    const char* title;",
              "    bool notify;", "    Journal journal;", "};",
              "constexpr CatalogEntry kCatalog[] = {"]
    modes = {"per_occurrence": "PerOccurrence", "transitions": "Transitions", "counter": "Counter"}
    for row in rows:
        oled = ", ".join(quote(line) for line in row["oled"] + [""] * (3 - len(row["oled"])))
        lines.append("    {Code::%s, %s, Severity::%s, {%s}, %d, %s, %s, Journal::%s}," % (
            row["symbol"], quote(row["symbol"]), row["severity"].title(), oled,
            len(row["oled"]), quote(row["title"]), str(row["notify"]).lower(), modes[row["journal"]]))
    lines += ["};", "constexpr std::size_t kCatalogSize = sizeof(kCatalog) / sizeof(kCatalog[0]);",
              "constexpr const CatalogEntry* find(std::uint16_t code) {",
              "    for (std::size_t i = 0; i < kCatalogSize; ++i) {",
              "        if (static_cast<std::uint16_t>(kCatalog[i].code) == code) return &kCatalog[i];",
              "    }", "    return nullptr;", "}", "}  // namespace diagnostics", "#endif", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail rather than write on drift")
    args = parser.parse_args(argv)
    expected = render(load_catalog())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != expected.encode("utf-8"):
            print("diag_catalog.h is stale; run python tools/generate_error_catalog.py", file=sys.stderr)
            return 1
        print("Diagnostic catalog header is current.")
        return 0
    OUTPUT.write_bytes(expected.encode("utf-8"))
    print("Generated", OUTPUT.name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
