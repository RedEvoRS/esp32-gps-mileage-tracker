"""Stamp Stage 4 with the current Git commit; run before each compile."""

from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[1]
HEADER = Path("firmware/04_trip_logger/firmware_version.h")
TOKEN = re.compile(r"[A-Za-z0-9][A-Za-z0-9._+-]{0,31}", re.ASCII)


def validate_version(version):
    # Reserve room for the suffix selected by DISPLAY_DEBUG at compile time.
    if not TOKEN.fullmatch(version) or not TOKEN.fullmatch(version + "+dbg"):
        raise ValueError("firmware version exceeds the protocol token budget")


def git_version(root):
    def git(*args):
        return subprocess.check_output(
            ["git", *args], cwd=root, text=True, encoding="utf-8",
            stderr=subprocess.DEVNULL).strip()

    commit = git("rev-parse", "--short=10", "HEAD")
    if not re.fullmatch(r"[0-9a-f]{10}", commit):
        raise ValueError("expected a ten-character Git commit")
    # Includes staged changes, deletions and renames, but no untracked files
    # (including untracked submodule content) or ignored build/secret files.
    dirty = git("status", "--porcelain", "--untracked-files=no",
                "--ignore-submodules=untracked")
    version = commit + ("-dirty" if dirty else "")
    validate_version(version)
    return version


def stamp(root=ROOT):
    root = Path(root)
    version = git_version(root)
    content = ('// Generated by tools/stamp_firmware_version.py; do not edit.\n'
               '#pragma once\n'
               f'#define FIRMWARE_VERSION_BASE "{version}"\n')
    target = root / HEADER
    if not target.exists() or target.read_text(encoding="ascii") != content:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="ascii", newline="\n")
    return version


if __name__ == "__main__":
    try:
        print(stamp())
    except (OSError, subprocess.CalledProcessError, ValueError):
        raise SystemExit("Cannot stamp firmware version: check Git and the repository checkout")
