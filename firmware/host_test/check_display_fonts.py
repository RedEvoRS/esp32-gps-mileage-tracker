"""Regenerate/check production glyph metrics from the installed U8g2 2.36.18.

Usage: python firmware/host_test/check_display_fonts.py <U8g2 directory> [--write]
The checked-in metrics keep layout tests independent of Arduino installations.
"""
import ast
from pathlib import Path
import re
import sys

FONTS = ("logisoso26_tr", "helvB14_tr", "logisoso38_tr")
CHARS = " +-0123456789:EKOSast"
TARGET = Path(__file__).resolve().parents[1] / "04_trip_logger/display_font_metrics.h"


def read_glyphs(data):
    # U8g2's 23-byte header, ASCII record lengths, and LSB-first glyph header;
    # signed fields use the excess-2^(n-1) encoding in u8g2_font.c.
    glyphs = {}
    pos = 23
    while data[pos] and data[pos + 1]:
        code, size = data[pos:pos + 2]
        bits = int.from_bytes(data[pos + 2:pos + size], "little")
        values = []
        for i, n in enumerate(data[4:9]):
            values.append((bits & ((1 << n) - 1)) - ((1 << (n - 1)) if i >= 2 else 0))
            bits >>= n
        glyphs[chr(code)] = values  # bitmap width/height, x/y offset, advance
        pos += size
    return glyphs


def generate(root):
    assert "version=2.36.18" in (root / "library.properties").read_text()
    source = (root / "src/clib/u8g2_fonts.c").read_text()
    lines = [
        "// Generated by host_test/check_display_fonts.py from U8g2 2.36.18.",
        "// Real glyph bitmap bounds and advances; y is relative to the baseline.",
        "#pragma once", "#include <cstdint>", "namespace display {",
        "enum class Font { Sats, Codes, Error };",
        "struct Glyph { int8_t width, height, x, y, advance; };",
        f'constexpr char kGlyphChars[] = "{CHARS}";',
        "constexpr Glyph kGlyphMetrics[3][sizeof(kGlyphChars)-1] = {",
    ]
    for font in FONTS:
        match = re.search(r"const uint8_t u8g2_font_" + font + r"\[\d+\][^=]*=\s*((?:\"(?:[^\"\\]|\\.)*\"\s*)+);", source)
        assert match, font
        data = b"".join(ast.literal_eval("b" + s) for s in re.findall(r'"(?:[^"\\]|\\.)*"', match[1]))
        glyphs = read_glyphs(data)
        lines.append(f"    {{ // u8g2_font_{font}")
        for ch in CHARS:
            values = ", ".join(map(str, glyphs[ch]))
            lines.append(f"        {{{values}}}, // {ch if ch != ' ' else 'space'}")
        lines.append("    },")
    lines.extend(["};", "} // namespace display", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    expected = generate(Path(sys.argv[1]))
    if "--write" in sys.argv[2:]:
        TARGET.write_text(expected, encoding="ascii")
    else:
        assert TARGET.read_text(encoding="ascii") == expected, "production font metrics differ from installed U8g2"
        print("Production glyph metrics match U8g2 2.36.18 (all three fonts).")
